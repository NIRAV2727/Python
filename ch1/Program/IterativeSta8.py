# Write a Python program to work with the Iterative statements in Python with suitable
# examples. i) while loop ii) for loop

print( "Example of while loop........ " )
start = 1
while start < 6 :
    print(start,end=" ")
    start+=1

print( "\n\nExample of for loop........ " )
for i in range(1,6) :
    print(i,end=" ")